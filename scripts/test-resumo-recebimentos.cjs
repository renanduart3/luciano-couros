const assert = require('node:assert/strict');
const { resumoRecebimentos } = require('../src/lib/resumoRecebimentos.ts');
const pagamento = (id, valorRecebido, aplicado, bonusGerado = 0) => ({ id, status:'ativo', statusPagamento:'compensado', valorRecebido, valorAplicado:aplicado, bonusGerado, bonusUtilizado:0, titulos:[], alocacoes:[{vendaId:'v127',valor:aplicado}] });
const anteriores = pagamento('a', 1300, 1300);
const excedente = pagamento('b', 4678, 908.8, 3769.2);
assert.deepEqual(resumoRecebimentos([anteriores,excedente], 'v127'), {confirmado:5978,aguardando:0,bonusGerado:3769.2,bonusUtilizado:0,aplicado:2208.8,outrosVales:0});
assert.equal(resumoRecebimentos([anteriores,anteriores], 'v127').confirmado,1300);
assert.equal(resumoRecebimentos([{...excedente,status:'recusado'}], 'v127').bonusGerado,0);
assert.equal(resumoRecebimentos([{...excedente,status:'cancelado'}], 'v127').confirmado,0);
const misto = {...pagamento('m',500,500),titulos:[{valor:200,status:'compensado'},{valor:300,status:'aguardando'},{valor:100,status:'recusado'}]};
assert.equal(resumoRecebimentos([misto]).confirmado,200);
assert.equal(resumoRecebimentos([misto]).aguardando,300);
const bonus = {...pagamento('c',0,100),bonusUtilizado:100};
assert.equal(resumoRecebimentos([bonus]).confirmado,0);
assert.equal(resumoRecebimentos([bonus]).bonusUtilizado,100);
const compartilhado = {...pagamento('s',1000,1000),alocacoes:[{vendaId:'v127',valor:250},{vendaId:'outro',valor:750}]};
assert.equal(resumoRecebimentos([compartilhado],'v127').aplicado,250);
assert.equal(resumoRecebimentos([compartilhado],'v127').outrosVales,750);
assert.equal(resumoRecebimentos([{...compartilhado,alocacoes:[{vendaId:'v127',valor:250,deletedAt:'2026-09-22'}]}],'v127').confirmado,0);
assert.equal(resumoRecebimentos([pagamento('c1',0.1,0.1),pagamento('c2',0.2,0.2)]).confirmado,0.3);
console.log('OK: excedente do vale 127, compensação parcial, recusa, cancelamento, bônus utilizado, compartilhamento, histórico e centavos');
